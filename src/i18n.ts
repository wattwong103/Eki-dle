import { regionOf, type RegionId } from "./prefectures";
import type { Lang } from "./types";

const REGION: Record<RegionId, { ja: string; en: string }> = {
  hokkaido: { ja: "北海道", en: "Hokkaido" },
  tohoku: { ja: "東北", en: "Tohoku" },
  kanto: { ja: "関東", en: "Kanto" },
  chubu: { ja: "中部", en: "Chubu" },
  kansai: { ja: "関西", en: "Kansai" },
  chugoku: { ja: "中国", en: "Chugoku" },
  shikoku: { ja: "四国", en: "Shikoku" },
  kyushu: { ja: "九州・沖縄", en: "Kyushu / Okinawa" },
};

export function regionName(pref: number, lang: Lang): string {
  return REGION[regionOf(pref)][lang];
}

export function regionIdName(id: RegionId, lang: Lang): string {
  return REGION[id][lang];
}

